import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import http from 'node:http';
import { execFileSync, spawn } from 'node:child_process';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import backend from 'git-http-backend';

const adb = (...args) => execFileSync('adb', args, { encoding: 'utf8' }).trim();
const root = resolve('.local', `sync-${Date.now()}`);
const bare = resolve(root, 'tasks.git');
const desktop = resolve(root, 'desktop');
await mkdir(root, { recursive: true });
const git = (dir, ...args) => execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim();
execFileSync('git', ['init', '--bare', '--initial-branch=main', bare]);
const requests = [];
const server = http.createServer((req, res) => {
  if (req.headers.authorization !== `Basic ${Buffer.from('tester:local-device-token').toString('base64')}`) { res.writeHead(401, { 'WWW-Authenticate': 'Basic realm="Git device test"' }); res.end(); return; }
  requests.push({ method: req.method, url: req.url });
  req.pipe(backend(req.url, (error, service) => {
    if (error) throw error;
    res.setHeader('content-type', service.type);
    const child = spawn(service.cmd, [...service.args, bare]);
    child.on('error', error => { throw error; });
    child.on('close', code => { assert.equal(code, 0); });
    child.stdout.pipe(service.createStream()).pipe(child.stdin);
  })).pipe(res);
});
await new Promise(resolve => server.listen(9847, '0.0.0.0', resolve));
adb('reverse', 'tcp:9847', 'tcp:9847');
adb('forward', 'tcp:9223', `localabstract:webview_devtools_remote_${adb('shell', 'pidof', 'io.anothertodo.mobile')}`);
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223');
const page = browser.contexts()[0].pages()[0];
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '同步', exact: true }).click();
  await page.getByLabel('仓库地址').fill('http://127.0.0.1:9847/tasks.git');
  await page.getByLabel('分支', { exact: true }).fill('main');
  await page.getByLabel('Git 用户名').fill('tester');
  await page.getByLabel('访问令牌').fill('local-device-token');
  await page.getByLabel('提交姓名').fill('Android device test');
  await page.getByLabel('提交邮箱').fill('android-test@example.invalid');
  await page.getByRole('button', { name: '立即同步', exact: true }).click();
  await page.locator('dialog .status').getByText('同步完成', { exact: true }).waitFor();
  const initial = JSON.parse(git(bare, 'show', 'main:tasks.jsonl').split('\n')[0]);
  assert.ok(initial.id);
  execFileSync('git', ['clone', bare, desktop]);
  git(desktop, 'config', 'user.name', 'Desktop device test'); git(desktop, 'config', 'user.email', 'desktop-test@example.invalid');
  const items = (await readFile(resolve(desktop, 'tasks.jsonl'), 'utf8')).trim().split('\n').map(JSON.parse);
  const target = items.find(item => item.title === '手机验收已编辑');
  target.notes = '来自电脑端的修改'; target.modified = new Date(Date.now() + 1000).toISOString();
  const remoteTask = { id: 'desktop-new', title: '电脑新增验收', status: 'todo', tags: ['同步'], notes: '', reminders: [], entry: new Date().toISOString(), modified: new Date().toISOString() };
  items.push(remoteTask);
  target.dependsOn = [remoteTask.id];
  await writeFile(resolve(desktop, 'tasks.jsonl'), items.map(item => JSON.stringify(item)).join('\n') + '\n');
  git(desktop, 'add', 'tasks.jsonl'); git(desktop, 'commit', '-m', 'Edit tasks on desktop'); git(desktop, 'push', 'origin', 'main');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '任务', exact: true }).click();
  await page.getByRole('button', { name: '添加任务', exact: true }).click();
  await page.getByLabel('一行一个任务').fill('手机同步新增验收 @none');
  await page.getByRole('button', { name: '检查任务', exact: true }).click();
  await page.getByRole('button', { name: '添加 1 个任务', exact: true }).click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '同步', exact: true }).click();
  await page.getByRole('button', { name: '立即同步', exact: true }).click();
  await page.locator('dialog .status').getByText('同步完成', { exact: true }).waitFor();
  const snapshot = await page.evaluate(() => JSON.parse(Native.invoke('load', '{}')).value);
  assert.equal(snapshot.state.tasks.find(item => item.id === target.id).notes, target.notes);
  assert.deepEqual(snapshot.state.tasks.find(item => item.id === target.id).dependsOn, [remoteTask.id]);
  assert.ok(snapshot.state.tasks.some(item => item.id === remoteTask.id));
  assert.ok(snapshot.state.tasks.some(item => item.title === '手机同步新增验收'));
  const remote = git(bare, 'show', 'main:tasks.jsonl').split('\n').filter(Boolean).map(JSON.parse);
  assert.deepEqual(new Set(remote.map(item => item.id)), new Set(snapshot.state.tasks.map(item => item.id)));
  git(desktop, 'pull', '--ff-only');
  const conflict = git(bare, 'show', 'main:tasks.jsonl').split('\n').filter(Boolean).map(JSON.parse);
  const remoteTarget = conflict.find(item => item.id === target.id);
  remoteTarget.notes = '电脑端较新的冲突修改'; remoteTarget.modified = new Date(Date.now() + 60000).toISOString();
  const removed = conflict.find(item => item.id === remoteTask.id);
  conflict.splice(conflict.indexOf(removed), 1, { id: remoteTask.id, deleted: true, modified: new Date().toISOString() });
  await writeFile(resolve(desktop, 'tasks.jsonl'), conflict.map(item => JSON.stringify(item)).join('\n') + '\n');
  git(desktop, 'add', 'tasks.jsonl'); git(desktop, 'commit', '-m', 'Concurrent update and deletion'); git(desktop, 'push', 'origin', 'main');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '任务', exact: true }).click();
  await page.getByText(target.title, { exact: true }).click();
  await page.getByLabel('备注', { exact: true }).fill('手机端并发修改');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.locator('#content').getByText(remoteTask.title, { exact: true }).click();
  await page.getByLabel('任务标题').fill('手机端同时修改被删除任务');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '同步', exact: true }).click();
  await page.getByRole('button', { name: '立即同步', exact: true }).click();
  await page.locator('dialog .status').getByText('同步完成', { exact: true }).waitFor();
  const merged = await page.evaluate(() => JSON.parse(Native.invoke('load', '{}')).value.state.tasks);
  assert.equal(merged.find(item => item.id === target.id).notes, remoteTarget.notes);
  assert.equal(merged.find(item => item.id === remoteTask.id).deleted, true);
  assert.deepEqual(merged.find(item => item.id === target.id).dependsOn, [remoteTask.id]);
  const latest = git(bare, 'show', 'main:tasks.jsonl').split('\n').filter(Boolean).map(JSON.parse);
  assert.equal(latest.find(item => item.id === target.id).notes, remoteTarget.notes);
  assert.equal(latest.find(item => item.id === remoteTask.id).deleted, true);
  assert.equal(errors.length, 0, errors.join('\n'));
  await writeFile('test-results/sync.json', JSON.stringify({ checks: ['empty private repository', 'authenticated native HTTP', 'push', 'desktop commit', 'concurrent branch edits', 'same task conflict', 'latest modified wins', 'deletion wins over edit', 'merge', 'pull', 'encrypted credentials'], requests, tasks: latest.length, errors }, null, 2));
  console.log('Android 与原生 Git 双端同步验收通过');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
