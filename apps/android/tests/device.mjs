import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';

const adb = (...args) => execFileSync('adb', args, { encoding: 'utf8' }).trim();
const packageId = 'io.anothertodo.mobile';
const output = new URL('../test-results/', import.meta.url);
await mkdir(output, { recursive: true });
let browser;
const connect = async () => {
  const pid = adb('shell', 'pidof', packageId);
  const port = 12000 + Number(pid) % 40000;
  adb('forward', `tcp:${port}`, `localabstract:webview_devtools_remote_${pid}`);
  browser = await chromium.connectOverCDP(`http://127.0.0.1:${port}`);
  const page = browser.contexts()[0].pages()[0];
  await page.getByRole('button', { name: '添加任务', exact: true }).waitFor();
  return page;
};
adb('shell', 'pm', 'clear', packageId);
adb('shell', 'pm', 'grant', packageId, 'android.permission.POST_NOTIFICATIONS');
adb('shell', 'appops', 'set', packageId, 'SCHEDULE_EXACT_ALARM', 'allow');
adb('shell', 'am', 'start', '-W', '-n', `${packageId}/.MainActivity`);
let page = await connect();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const add = async input => {
  await page.getByRole('button', { name: '添加任务', exact: true }).click();
  await page.getByLabel('一行一个任务').fill(input);
  await page.getByRole('button', { name: '检查任务', exact: true }).click();
  await page.getByRole('button', { name: '添加 1 个任务', exact: true }).click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
};
await add('明天 18:30 手机验收 #工作 proj:Android 很急 >>保留备注');
await page.getByText('手机验收', { exact: true }).click();
await page.getByLabel('任务标题').fill('手机验收已编辑');
await page.getByLabel('备注', { exact: true }).fill('支持多行备注\n第二行');
await page.getByRole('button', { name: '关闭', exact: true }).click();
await page.getByRole('button', { name: '完成 手机验收已编辑', exact: true }).click();
await page.getByRole('button', { name: '撤销操作', exact: true }).click();
await page.getByText('手机验收已编辑', { exact: true }).waitFor();
await add('今天 每日验收 *每天 @none');
await page.getByRole('button', { name: '完成 每日验收', exact: true }).click();
await page.getByText('每日验收', { exact: true }).waitFor();
await page.getByRole('button', { name: '更多', exact: true }).click();
await page.getByRole('button', { name: '全部任务', exact: true }).click();
assert.equal(await page.getByText('每日验收', { exact: true }).count(), 2);
await page.getByLabel('搜索与查询').fill('has:recur');
await page.getByText('手机验收已编辑', { exact: true }).waitFor({ state: 'hidden' });
await page.getByLabel('搜索与查询').fill('');
await page.getByText('手机验收已编辑', { exact: true }).click();
await page.getByText('其他操作', { exact: true }).click();
await page.getByRole('button', { name: '添加子任务', exact: true }).click();
await page.getByLabel('一行一个任务').fill('子任务验收 @none');
await page.getByRole('button', { name: '检查任务', exact: true }).click();
await page.getByRole('button', { name: '添加 1 个任务', exact: true }).click();
await page.getByText('子任务验收', { exact: true }).waitFor();
await page.getByRole('button', { name: '完成 手机验收已编辑', exact: true }).click();
await page.getByRole('button', { name: '连同子任务完成', exact: true }).click();
await page.getByRole('button', { name: '撤销操作', exact: true }).click();
await page.getByText('手机验收已编辑', { exact: true }).click();
await page.getByText('其他操作', { exact: true }).click();
await page.getByRole('button', { name: '删除任务', exact: true }).click();
await page.getByRole('button', { name: '确认删除', exact: true }).click();
await page.getByRole('button', { name: '撤销操作', exact: true }).click();
await page.getByText('手机验收已编辑', { exact: true }).waitFor();
await page.getByRole('button', { name: '统计', exact: true }).click();
await page.getByText('近七天完成', { exact: true }).waitFor();
await page.getByRole('button', { name: '任务', exact: true }).click();
await page.screenshot({ path: new URL('tasks.png', output).pathname.slice(1), fullPage: true });
const before = await page.evaluate(() => JSON.parse(Native.invoke('load', '{}')));
assert.equal(before.ok, true);
const parent = before.value.state.tasks.find(task => task.title === '手机验收已编辑');
assert.equal(parent.notes, '支持多行备注\n第二行');
assert.ok(parent.reminders.every(reminder => typeof reminder.id === 'string' && reminder.id.length > 0));
assert.equal(before.value.state.tasks.find(task => task.title === '子任务验收').parent, parent.id);
await browser.close();
adb('shell', 'am', 'force-stop', packageId);
adb('shell', 'am', 'start', '-W', '-n', `${packageId}/.MainActivity`);
page = await connect();
const after = await page.evaluate(() => JSON.parse(Native.invoke('load', '{}')));
assert.deepEqual(after.value.state.tasks, before.value.state.tasks);
assert.equal(errors.length, 0, errors.join('\n'));
await writeFile(new URL('device.json', output), JSON.stringify({ checks: ['create', 'edit', 'multiline notes', 'complete', 'undo', 'recurrence', 'query', 'subtasks', 'cascade', 'delete', 'stats', 'process restart persistence'], tasks: after.value.state.tasks.length, errors }, null, 2));
await browser.close();
console.log('Android WebView 端到端验收通过');
