const adb = (...args) => execFileSync('adb', args, { encoding: 'utf8', timeout: 20000 }).trim();
const parser = new XMLParser({ ignoreAttributes: false, attributeNamePrefix: '' });
const nodes = value => {
  if (!value || typeof value !== 'object') return [];
  if (Array.isArray(value)) return value.flatMap(nodes);
  return [...(value.bounds ? [value] : []), ...Object.values(value).filter(item => typeof item === 'object').flatMap(nodes)];
};
const snapshot = () => { adb('shell', 'uiautomator', 'dump', '/sdcard/atd-release.xml'); return nodes(parser.parse(adb('shell', 'cat', '/sdcard/atd-release.xml'))); };
const waitNode = async predicate => {
  const deadline = Date.now() + 12000;
  while (Date.now() < deadline) {
    const node = snapshot().find(predicate); if (node) return node;
    await setTimeout(200);
  }
  throw new Error('正式 APK 未显示指定界面元素');
};
