import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

const adb = (...args) => execFileSync('adb', args, { encoding: 'utf8' }).trim();
const pkg = 'io.anothertodo.mobile';
adb('shell', 'pm', 'clear', pkg);
adb('shell', 'pm', 'grant', pkg, 'android.permission.POST_NOTIFICATIONS');
adb('shell', 'appops', 'set', pkg, 'SCHEDULE_EXACT_ALARM', 'allow');
adb('shell', 'am', 'start', '-W', '-n', `${pkg}/.MainActivity`);
const pid = adb('shell', 'pidof', pkg), port = 12000 + Number(pid) % 40000;
adb('forward', `tcp:${port}`, `localabstract:webview_devtools_remote_${pid}`);
const browser = await chromium.connectOverCDP(`http://127.0.0.1:${port}`);
const page = browser.contexts()[0].pages()[0];
const snapshot = () => page.evaluate(() => JSON.parse(Native.invoke('load', '{}')).value.state);
const add = async text => {
  await page.getByRole('button', { name: '添加任务', exact: true }).click();
  await page.getByLabel('一行一个任务').fill(text);
  await page.getByRole('button', { name: '检查任务', exact: true }).click();
  await page.getByRole('button', { name: /^添加 \d+ 个任务$/ }).click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
};
try {
  await add('整理资料 @none\n写报告 after:整理资料 @none\n提交 before:发邮件 @none\n发邮件 @none');
  let state = await snapshot(); assert.equal(state.tasks.length, 4);
  const collect = state.tasks.find(task => task.title === '整理资料');
  const report = state.tasks.find(task => task.title === '写报告');
  assert.deepEqual(report.dependsOn, [collect.id]);
  assert.deepEqual(state.tasks.find(task => task.title === '发邮件').dependsOn, [state.tasks.find(task => task.title === '提交').id]);
  await page.locator('#content').getByText(report.title, { exact: true }).click();
  await page.getByLabel('备注', { exact: true }).fill('自动保存第一行\n第二行包含完整说明。');
  await page.getByText('已经保存', { exact: true }).waitFor();
  await page.getByLabel('任务标题').fill('写报告并核对长篇材料');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  state = await snapshot(); assert.equal(state.tasks.find(task => task.id === report.id).title, '写报告并核对长篇材料');
  assert.equal(state.tasks.find(task => task.id === report.id).notes, '自动保存第一行\n第二行包含完整说明。');
  assert.deepEqual(state.tasks.find(task => task.id === report.id).dependsOn, [collect.id]);
  await add('整理资料 @none');
  await page.getByRole('button', { name: '添加任务', exact: true }).click();
  await page.getByLabel('一行一个任务').fill('核对材料 after:整理资料 @none');
  await page.getByRole('button', { name: '检查任务', exact: true }).click();
  await page.getByRole('button', { name: `选择依赖 ${collect.id} 整理资料`, exact: true }).click();
  await page.getByRole('button', { name: '添加 1 个任务', exact: true }).click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  state = await snapshot(); assert.deepEqual(state.tasks.find(task => task.title === '核对材料').dependsOn, [collect.id]);
  const checkTask = state.tasks.find(task => task.title === '核对材料');
  await page.locator('#content').getByText(checkTask.title, { exact: true }).click();
  await page.getByLabel('任务标题').fill('核对材料 before:发邮件');
  await page.getByText('已经保存', { exact: true }).waitFor();
  state = await snapshot(); assert.ok(state.tasks.find(task => task.title === '发邮件').dependsOn.includes(checkTask.id));
  await page.getByLabel('任务标题').fill(`核对材料 after:${checkTask.id}`);
  await page.getByText('保存未完成', { exact: true }).waitFor();
  state = await snapshot(); assert.deepEqual(state.tasks.find(task => task.id === checkTask.id).dependsOn, [collect.id]);
  await page.getByLabel('任务标题').fill('核对材料并检查附件');
  await page.getByText('已经保存', { exact: true }).waitFor();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.screenshot({ path: 'test-results/pixel-tasks.png', fullPage: true });
  await page.getByRole('button', { name: '完成 整理资料', exact: true }).first().click();
  await page.locator('#content').getByText('写报告并核对长篇材料', { exact: true }).click();
  await page.getByRole('button', { name: '完成任务', exact: true }).click();
  state = await snapshot(); assert.equal(state.tasks.find(task => task.id === report.id).status, 'done');
  await writeFile('test-results/workflows.json', JSON.stringify({ checks: ['one task per line', 'atomic batch', 'forward references', 'before edges', 'ambiguous candidate click', 'automatic save', 'close flush', 'dependencies preserved', 'dependency completion gating'], tasks: state.tasks.length }, null, 2));
  console.log('Android 批量添加、依赖确认与自动保存验收通过');
} finally { await browser.close(); }
