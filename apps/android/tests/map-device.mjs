const pkg = 'io.anothertodo.mobile';
adb('shell', 'pm', 'clear', pkg);
adb('shell', 'am', 'start', '-W', '-n', `${pkg}/.MainActivity`);
const pid = adb('shell', 'pidof', pkg), port = 12000 + Number(pid) % 40000;
adb('forward', `tcp:${port}`, `localabstract:webview_devtools_remote_${pid}`);
const browser = await chromium.connectOverCDP(`http://127.0.0.1:${port}`, { timeout: 20000 });
const page = browser.contexts()[0].pages()[0];
page.setDefaultTimeout(20000);
const errors = []; page.on('pageerror', error => errors.push(error.message));
const snapshot = () => page.evaluate(() => JSON.parse(Native.invoke('load', '{}')).value.state);
