import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const adb = (...args) => execFileSync('adb', args, { encoding: 'utf8' }).trim();
const pid = adb('shell', 'pidof', 'io.anothertodo.mobile'), port = 12000 + Number(pid) % 40000;
adb('forward', `tcp:${port}`, `localabstract:webview_devtools_remote_${pid}`);
const browser = await chromium.connectOverCDP(`http://127.0.0.1:${port}`);
const page = browser.contexts()[0].pages()[0];
const shot = async name => { adb('shell', 'screencap', '-p', `/sdcard/${name}.png`); adb('pull', `/sdcard/${name}.png`, `test-results/${name}.png`); };
try {
  await page.locator('#navigation').getByRole('button', { name: '任务', exact: true }).click();
  const today = await page.evaluate(() => { const date = new Date(); return `${date.getFullYear()}-${String(date.getMonth()+1).padStart(2,'0')}-${String(date.getDate()).padStart(2,'0')}`; });
  await page.getByRole('button', { name: '添加任务', exact: true }).click();
  await page.getByLabel('一行一个任务').fill(`${today} 18:00 核对季度报告中所有来源、图表说明与较长的中文任务标题 高 @none\n${today} 19:00 发送会议材料 低 @none\n明天 18:00 安排下一阶段的材料整理与跨部门项目沟通 高 @none\n安排休息 @none`);
  await page.getByRole('button', { name: '检查任务', exact: true }).click();
  await shot('pixel-batch-review');
  await page.getByRole('button', { name: '添加 4 个任务', exact: true }).click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  await page.locator('#navigation').getByRole('button', { name: '日程', exact: true }).click();
  await page.getByRole('button', { name: '月历', exact: true }).click();
  assert.ok(await page.locator('.calendar-day').count() >= 28);
  await page.getByRole('button', { name: new RegExp(`^${today}，`) }).click();
  await page.locator('#content').getByText('发送会议材料', { exact: true }).waitFor();
  await shot('pixel-month');
  await page.getByRole('button', { name: '周历', exact: true }).click();
  assert.equal(await page.locator('.week-agenda section').count(), 7);
  await shot('pixel-week');
  await page.getByRole('button', { name: '日历', exact: true }).click();
  await page.locator('#content').getByText('发送会议材料', { exact: true }).waitFor();
  await page.getByRole('button', { name: '重要度', exact: true }).click();
  await page.locator('#content').getByText('安排休息', { exact: true }).waitFor();
  await page.getByRole('button', { name: '四象限', exact: true }).click();
  assert.equal(await page.locator('.quadrant').count(), 4);
  assert.ok((await page.locator('.q0').innerText()).includes('核对季度报告'));
  await page.getByRole('button', { name: '查看重要不紧急', exact: true }).click();
  assert.ok((await page.locator('.q1').innerText()).includes('安排下一阶段'));
  await page.getByRole('button', { name: '查看不重要但紧急', exact: true }).click();
  assert.ok((await page.locator('.q2').innerText()).includes('发送会议材料'));
  await page.getByRole('button', { name: '查看不重要不紧急', exact: true }).click();
  assert.ok((await page.locator('.q3').innerText()).includes('安排休息'));
  await page.getByRole('button', { name: '查看重要且紧急', exact: true }).click();
  await shot('pixel-matrix');
  await page.getByRole('button', { name: '月历', exact: true }).click();
  await page.getByRole('button', { name: '下个月', exact: true }).click();
  await page.getByRole('button', { name: '添加任务', exact: true }).click();
  await page.getByLabel('一行一个任务').fill('选中日期新增任务 @none');
  await page.getByRole('button', { name: '检查任务', exact: true }).click();
  await page.getByRole('button', { name: '添加 1 个任务', exact: true }).click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  const state = await page.evaluate(() => JSON.parse(Native.invoke('load', '{}')).value.state);
  const added = state.tasks.find(task => task.title === '选中日期新增任务');
  assert.notEqual(added.due.slice(0, 7), today.slice(0, 7));
  await page.locator('#navigation').getByRole('button', { name: '统计', exact: true }).click();
  await page.getByLabel('显示完成方块').check();
  await page.locator('.activity-cell').first().waitFor();
  const count = state.tasks.filter(task => task.status === 'done').length;
  await page.getByRole('button', { name: `${today} 完成 ${count} 个任务`, exact: true }).click();
  await page.getByText(`${today} · 完成 ${count} 个任务`, { exact: true }).waitFor();
  await shot('pixel-activity');
  await page.getByLabel('完成记录范围').selectOption('52');
  await page.waitForFunction(() => document.querySelectorAll('.activity-grid button').length === 364);
  await page.getByLabel('显示完成方块').uncheck();
  await page.locator('.activity-grid').waitFor({ state: 'hidden' });
  await writeFile('test-results/calendar.json', JSON.stringify({ checks: ['month grid', 'seven-day week', 'day view', 'priority view', 'four quadrants', 'selected date adding', 'long titles', 'actual completion heatmap', 'persisted optional activity', 'full year scrolling'], tasks: state.tasks.length, today }, null, 2));
  console.log('Android 日历、周历、月历、四象限与完成方块验收通过');
} finally { await browser.close(); }
